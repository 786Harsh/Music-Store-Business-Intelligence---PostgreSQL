-- ============================================================
-- Q30 - Measure Revenue by Employee
--
-- Business Question:
-- How much revenue is generated by customers assigned to each employee?
--
-- Purpose:
-- Compares employee portfolios by customers, invoices, and revenue.
-- ============================================================
